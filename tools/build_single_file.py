"""Build the single-file edition: every module, the icon and the README in one .py file.

The README is embedded twice: the PDF the title's right-click opens, and its
Markdown for the fallback window.

    python tools/build_single_file.py            -> dist/SpaceNavigator_Mapper_<version>_Complete.py

The output runs with `py SpaceNavigator_Mapper_<version>_Complete.py` and keeps
its configs/ folder beside itself, exactly like the source tree. Modules are
served from memory by a small import hook, under their normal names.
"""

import base64
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "spnav_mapper"
ICON = PACKAGE / "resources" / "SpaceNavigatorMapper.ico"
README_MD = PACKAGE / "resources" / "SpaceNavigator_Mapper_README.md"  # right-click the title
README_PDF = PACKAGE / "resources" / "SpaceNavigator_Mapper_README.pdf"

HEADER = '''"""SpaceNavigator Mapper {version} — complete single-file edition.
Logic by Don Muddiman.

Windows requirements: py -m pip install PyQt5 hidapi pywinusb
Run: py {filename}

All application source, the default icon and the README are included below.
Modules load directly from this file in memory, preserving their original
namespaces. Configuration files are stored in configs beside this script.
Generated by tools/build_single_file.py; edit the source tree, not this file.
"""
import base64
import importlib.abc
import importlib.util
from pathlib import Path
import sys

_SINGLE_FILE_ENTRY = str(Path(__file__).resolve())
_EMBEDDED_SOURCES = {{}}
'''

FOOTER = '''

class _EmbeddedApplication(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    """Serve the application's bundled modules without extracting files."""

    def find_spec(self, fullname, path=None, target=None):
        if fullname in _EMBEDDED_SOURCES:
            package = fullname in _PACKAGES
            return importlib.util.spec_from_loader(fullname, self, is_package=package)
        return None

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        module.__file__ = _SINGLE_FILE_ENTRY
        module._single_file_entry = _SINGLE_FILE_ENTRY
        module._single_file_icon = _EMBEDDED_ICON
        module._single_file_readme = _EMBEDDED_README
        module._single_file_readme_pdf = _EMBEDDED_README_PDF
        if "__compiled__" in globals():
            module.__compiled__ = globals()["__compiled__"]
        code = compile(_EMBEDDED_SOURCES[module.__name__],
                       _SINGLE_FILE_ENTRY + ":" + module.__name__, "exec")
        exec(code, module.__dict__)


sys.meta_path.insert(0, _EmbeddedApplication())

if __name__ == "__main__":
    from spnav_mapper.bootstrap import launch
    raise SystemExit(launch())
'''


def escape(source):
    """Make module source safe inside a regular triple-quoted string."""
    return source.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def module_name(path):
    rel = path.relative_to(ROOT).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def build(out_dir=ROOT / "dist"):
    version = re.search(r'VERSION = "([^"]+)"', (PACKAGE / "version.py").read_text(encoding="utf-8")).group(1)
    filename = f"SpaceNavigator_Mapper_{version}_Complete.py"
    files = sorted(p for p in PACKAGE.rglob("*.py") if p.name != "__main__.py")
    packages = sorted(module_name(p) for p in files if p.name == "__init__.py")
    parts = [HEADER.format(version=version, filename=filename)]
    for path in files:
        name = module_name(path)
        parts.append(
            f"\n# ==================== {name} ====================\n"
            f"_EMBEDDED_SOURCES['{name}'] = \"\"\"{escape(path.read_text(encoding='utf-8'))}\"\"\"\n"
        )
    parts.append(f"\n_PACKAGES = {tuple(packages)!r}\n")
    parts.append(f"_EMBEDDED_ICON = '{base64.b64encode(ICON.read_bytes()).decode('ascii')}'\n")
    readme = base64.b64encode(README_MD.read_bytes()).decode("ascii")
    parts.append(f"_EMBEDDED_README = base64.b64decode('{readme}').decode('utf-8')\n")
    # The PDF in lines of 100 characters (b64decode skips the line breaks).
    pdf = base64.b64encode(README_PDF.read_bytes()).decode("ascii")
    lines = "\n".join(pdf[i : i + 100] for i in range(0, len(pdf), 100))
    parts.append(f'_EMBEDDED_README_PDF = base64.b64decode("""\n{lines}\n""")\n')
    parts.append(FOOTER)
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / filename
    target.write_text("".join(parts), encoding="utf-8", newline="\n")
    compile(target.read_text(encoding="utf-8"), str(target), "exec")  # fail loudly if escaping broke
    return target


if __name__ == "__main__":
    print(build(pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "dist"))
